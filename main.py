# Metrics
INFER_COUNT = Counter("infer_requests_total", "Total inference requests")
INFER_LATENCY = Histogram("infer_latency_seconds", "Inference latency")

@app.route("/metrics")
def metrics():
    """Prometheus metrics endpoint"""
    return generate_latest(), 200, {"Content-Type": CONTENT_TYPE_LATEST}

@app.before_request
def before_request():
    """Store request start time for latency calculation"""
    request.start_time = time.time()

@app.after_request
def after_request(response):
    """Record metrics after request is processed"""
    if request.endpoint == "infer":
        INFER_COUNT.inc()
        if hasattr(request, 'start_time'):
            INFER_LATENCY.observe(time.time() - request.start_time)
    return response

