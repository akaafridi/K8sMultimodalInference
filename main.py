def decode_image(image_data):
    """
    Decode an image from a URL or base64 string.
    
    Args:
        image_data (str): A URL or base64-encoded image
        
    Returns:
        PIL.Image: The decoded image
    """
    try:
        # Check if the image data is a URL
        if image_data.startswith(('http://', 'https://')):
            logger.info("Downloading image from URL")
            headers = {
                'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
            }
            response = requests.get(image_data, headers=headers)
            response.raise_for_status()  # Raise an error for bad status codes
            image = Image.open(BytesIO(response.content))
            return image
        
        # Otherwise, assume it's a base64-encoded string
        else:
            logger.info("Decoding base64 image")
            # Remove the data URL prefix if present
            if ',' in image_data:
                image_data = image_data.split(',')[1]
                
            # Decode base64 string
            image_bytes = base64.b64decode(image_data)
            image = Image.open(BytesIO(image_bytes))
            return image
            
    except Exception as e:
        logger.error(f"Error decoding image: {str(e)}")
        raise ValueError(f"Failed to decode image: {str(e)}")

@app.route('/infer', methods=['POST'])
def infer():
    """
    Model inference endpoint. Accepts JSON input for image captioning.
    
    Example payload:
    {
        "image": "base64-encoded image or image URL"
    }
    
    Returns:
    {
        "predictions": "image caption result",
        "model_version": "version of the model used"
    }
    """
    try:
        # Get JSON data from request
        request_data = request.get_json()
        
        if not request_data:
            return jsonify({"error": "No input data provided"}), 400
        
        image_data = request_data.get('image')
        if not image_data:
            return jsonify({"error": "Missing 'image' field in request"}), 400
        
        # Log the inference request (truncate large payloads)
        if len(image_data) > 100:
            log_data = image_data[:50] + "..." + image_data[-50:]
        else:
            log_data = image_data
            
        logger.info(f"Received inference request with image data: {log_data}")
        
        # Process the image
        try:
            image = decode_image(image_data)
            logger.info(f"Image decoded successfully: {image.size}")
            
            # Process with BLIP model
            inputs = processor(image, return_tensors="pt").to("cuda")
            output_ids = model.generate(**inputs)
            caption = processor.decode(output_ids[0], skip_special_tokens=True)
            
            # Return the results
            result = {
                "predictions": caption,
                "model_version": model.config._name_or_path
            }
            
            logger.info("Inference completed successfully")
            return jsonify(result), 200
            
        except ValueError as ve:
            return jsonify({"error": str(ve)}), 400
    
    except Exception as e:
        logger.error(f"Error during inference: {str(e)}")
        return jsonify({"error": f"Error processing request: {str(e)}"}), 500

